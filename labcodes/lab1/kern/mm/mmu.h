/*
 * ============================================================================
 * kern/mm/mmu.h —— 内存管理单元相关的最基础常量
 * ============================================================================
 * lab1 只用到 PGSIZE / PGSHIFT 这两个值：
 *   - entry.S 里 ".align PGSHIFT" 让内核栈按 4KB 对齐；
 *   - memlayout.h 里用 PGSIZE 算出 KSTACKSIZE。
 * 由"页大小 = 4KB"这个约定，才有后面所有实验的页式内存管理（lab2 展开）。
 * ============================================================================
 */

#ifndef __KERN_MM_MMU_H__
#define __KERN_MM_MMU_H__

/* 一个（物理/虚拟）页面的大小：4096 字节 = 4KB，RISC-V 的常见配置。*/
#define PGSIZE          4096                    // bytes mapped by a page
/* PGSIZE 的以 2 为底的对数，即 log2(4096) = 12。
 *   好处：除以/乘以页大小可以写成移位，汇编里 .align 也只能接受指数。*/
#define PGSHIFT         12                      // log2(PGSIZE)

#endif /* !__KERN_MM_MMU_H__ */
